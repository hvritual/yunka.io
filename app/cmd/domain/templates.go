func wireTemplate(spec Spec, packageImport string) string {
	var b strings.Builder
	b.WriteString("// Code generated by yunka domain; DO NOT EDIT.\n\n")
	b.WriteString("package wire\n\n")
	fmt.Fprintf(&b, "import (\n\t\"gorm.io/gorm\"\n\tapplication %q\n\tpersistence %q\n", packageImport+"/application", packageImport+"/infrastructure/persistence")
	if spec.REST.Enabled {
		fmt.Fprintf(&b, "\trest %q\n", packageImport+"/transport/rest")
	}
	if spec.RPC.Enabled {
		fmt.Fprintf(&b, "\trpc %q\n", packageImport+"/transport/rpc")
	}
	b.WriteString(")\n\n")
	b.WriteString("type Bundle struct {\n\tService application.Service\n")
	if spec.REST.Enabled {
		b.WriteString("\tREST *rest.Handler\n")
	}
	if spec.RPC.Enabled {
		b.WriteString("\tRPC *rpc.Server\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("func Build(database *gorm.DB) (Bundle, error) {\n\tscopes, err := persistence.NewScopeFactory(database)\n\tif err != nil { return Bundle{}, err }\n\tservice, err := application.NewService(scopes)\n\tif err != nil { return Bundle{}, err }\n\tbundle := Bundle{Service: service}\n")
	if spec.REST.Enabled {
		b.WriteString("\tbundle.REST = rest.New(service)\n")
	}
	if spec.RPC.Enabled {
		b.WriteString("\tbundle.RPC = rpc.New(service)\n")
	}
	b.WriteString("\treturn bundle, nil\n}\n")
	return b.String()
}
