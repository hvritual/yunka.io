func writeBusinessFields(b *strings.Builder, fields []Field) {
	for _, field := range fields {
		typeName, _ := goType(field.Type)
		fmt.Fprintf(b, "\t%s %s `json:\"%s\"`\n", exportedIdentifier(field.Name), typeName, jsonName(field.Name))
	}
}

func writeInputAssignments(b *strings.Builder, fields []Field, source string) {
	for _, field := range fields {
		f := exportedIdentifier(field.Name)
		fmt.Fprintf(b, "\t\t%s: %s.%s,\n", f, source, f)
	}
}

