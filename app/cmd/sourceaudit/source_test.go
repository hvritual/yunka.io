func TestWorkspaceAndReplaceCoverage(t *testing.T) {
	for _, mode := range []string{"workspace", "relative_replace", "absolute_replace", "absolute_workspace"} {
		t.Run(mode, func(t *testing.T) {
			p := fixturePolicy()
			p.Modules = []ModulePolicy{{Path: "a", Workspace: "off", Profiles: []string{"host"}}, {Path: "b", Workspace: "off", Profiles: []string{"host"}}}
			root := fixture(t, p, map[string]string{"a/go.mod": "module example.com/asteroid\ngo 1.23.0\n", "b/go.mod": "module example.com/belt\ngo 1.23.0\n", "a/main.go": "package asteroid\nimport _ \"example.com/belt\"\n", "b/main.go": "package belt\n"})
			if e := os.Remove(filepath.Join(root, "go.mod")); e != nil {
				t.Fatal(e)
			}
			switch mode {
			case "workspace", "absolute_workspace":
				uses := "./a\n./b"
				if mode == "absolute_workspace" {
					uses = fmt.Sprintf("%q\n%q", filepath.Join(root, "a"), filepath.Join(root, "b"))
				}
				put(t, root, "go.work", "go 1.23.0\nuse (\n"+uses+"\n)\n")
				for i := range p.Modules {
					p.Modules[i].Workspace = "go.work"
				}
			case "relative_replace", "absolute_replace":
				target := "../b"
				if mode == "absolute_replace" {
					target = fmt.Sprintf("%q", filepath.Join(root, "b"))
				}
				put(t, root, "a/go.mod", "module example.com/asteroid\ngo 1.23.0\nrequire example.com/belt v0.0.0\nreplace example.com/belt => "+target+"\n")
			}
			writePolicy(t, root, p)
			r := execute(t, root)
			expect(t, r, Pass, "", "")
			if r.Analysis.CheckedGoFiles != 2 || len(r.Modules) != 2 || len(r.References) == 0 {
				t.Fatalf("missing topology evidence: %+v", r)
			}
		})
	}
	t.Run("versioned_manifest_inventory", func(t *testing.T) {
		p := fixturePolicy()
		root := fixture(t, p, map[string]string{"base.go": "package nebula\n", "go.mod": "module example.com/nebula\ngo 1.23.0\nreplace example.com/unused v1.0.0 => example.com/other v1.0.0\n"})
		r := execute(t, root)
		expect(t, r, Pass, "", "")
		if len(r.References) != 1 || r.References[0].Disposition != "versioned-dependency" {
			t.Fatal("missing versioned replace")
		}
	})
}

func TestStrictPolicy(t *testing.T) {
	p := fixturePolicy()
	b, e := json.Marshal(p)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadPolicy(b); e != nil {
		t.Fatal(e)
	}
	for name, raw := range map[string]string{"empty": "{}", "duplicate": strings.Replace(string(b), `"schemaVersion":1`, `"schemaVersion":1,"schemaVersion":1`, 1), "unknown": strings.Replace(string(b), `"schemaVersion":1`, `"schemaVersion":1,"surprise":true`, 1), "trailing": string(b) + "{}", "null": strings.Replace(string(b), `"tags":[]`, `"tags":null`, 1)} {
		t.Run(name, func(t *testing.T) {
			if _, e := ReadPolicy([]byte(raw)); e == nil {
				t.Fatalf("accepted invalid policy: %s", raw)
			}
		})
	}
	for _, change := range []func(*Policy){func(p *Policy) { p.Modules[0].Path = "../escape" }, func(p *Policy) { p.Modules[0].Profiles = []string{"missing"} }, func(p *Policy) { p.Components[0].Allow = []string{"missing"} }, func(p *Policy) { p.Components[0].DenyImports = []string{"example.com/bad?path"} }, func(p *Policy) {
		p.Exclusions = []Exclusion{{Path: ".", Kind: "fixture", Reason: "cannot exclude all"}}
	}, func(p *Policy) { p.Profiles = append(p.Profiles, p.Profiles[0]) }} {
		p := fixturePolicy()
		change(&p)
		if e := p.Validate(); e == nil {
			t.Fatalf("accepted invalid policy: %+v", p)
		}
	}
}

func TestBackendFailureCoverageAndDrift(t *testing.T) {
	for _, mode := range []string{"error", "empty", "omitted", "new_original", "delete_original", "mutate_policy", "mutate_projection"} {
		t.Run(mode, func(t *testing.T) {
			root := fixture(t, fixturePolicy(), map[string]string{"base.go": "package nebula\n"})
			run := func(ctx context.Context, binary, dir string, env []string, args ...string) ([]byte, error) {
				if args[0] != "list" {
					return runGo(ctx, binary, dir, env, args...)
				}
				switch mode {
				case "error":
					return nil, fmt.Errorf("backend fault")
				case "empty":
					return []byte(""), nil
				case "omitted":
					return []byte(`{"ImportPath":"other","Name":"other"}`), nil
				case "new_original":
					put(t, root, "new.go", "package nebula\n")
				case "delete_original":
					if e := os.Remove(filepath.Join(root, "base.go")); e != nil {
						t.Fatal(e)
					}
				case "mutate_policy":
					put(t, root, "policy.json", "{}")
				case "mutate_projection":
					put(t, dir, "go.sum", "unexpected tool mutation\n")
				}
				return runGo(ctx, binary, dir, env, args...)
			}
			r, e := check(context.Background(), root, "policy.json", run)
			if e != nil {
				t.Fatal(e)
			}
			rule := "AG-SRC-007"
			if mode == "error" || mode == "empty" {
				rule = "AG-SRC-000"
			}
			if mode == "omitted" {
				rule = "AG-SRC-003"
			}
			expect(t, r, Incomplete, rule, "")
		})
	}
}

func TestReportConservation(t *testing.T) {
	p := fixturePolicy()
	p.Exclusions = []Exclusion{{Path: "fixture", Kind: "fixture", Reason: "Deliberate standalone malformed fixture"}}
	root := fixture(t, p, map[string]string{"base.go": "package nebula\n", "fixture/x.go": "broken source", "fixture/go.mod": "invalid fixture manifest"})
	r := execute(t, root)
	expect(t, r, Pass, "", "")
	a := r.Analysis
	if a.CheckedGoFiles+a.ExcludedGoFiles+a.UncoveredGoFiles != r.Inventory.GoFiles {
		t.Fatal("nonconserving inventory")
	}
	if !reflect.DeepEqual(r.Files[0].Profiles, []string{"host"}) {
		t.Fatalf("missing coverage %+v", r.Files)
	}
}
