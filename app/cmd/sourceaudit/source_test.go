func TestSourceAndPolicyFailuresAreNotPass(t *testing.T) {
	cases := []struct{ name, file, body, rule string }{
		{"unknown_module", "new/go.mod", "module example.com/new\ngo 1.23.0\n", "AG-SRC-001"},
		{"parse_error", "new.go", "package nebula\nfunc broken(\n", "AG-SRC-000"},
		{"missing_dependency", "new.go", "package nebula\nimport _ \"example.invalid/notcached\"\n", "AG-SRC-000"},
		{"ignored_filename", "_hidden.go", "package nebula\n", "AG-SRC-003"},
		{"uncovered_tag", "new.go", "//go:build neverdeclared\n\npackage nebula\n", "AG-SRC-003"},
		{"invalid_workspace", "go.work", "this is not a workspace\n", "AG-SRC-001"},
		{"escape_replace", "go.mod", "module example.com/nebula\ngo 1.23.0\nreplace example.com/dependency => ../outside\n", "AG-SRC-008"},
		{"missing_replace", "go.mod", "module example.com/nebula\ngo 1.23.0\nreplace example.com/dependency => ./missing\n", "AG-SRC-008"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := fixture(t, fixturePolicy(), map[string]string{"base.go": "package nebula\n", tc.file: tc.body})
			r := execute(t, root)
			expect(t, r, Incomplete, tc.rule, "")
			if !r.SourceUnchanged {
				t.Fatal("failed check wrote original source")
			}
		})
	}
	t.Run("unknown_component", func(t *testing.T) {
		p := fixturePolicy()
		p.Components[0].Path = "known"
		root := fixture(t, p, map[string]string{"other/go.go": "package other\n"})
		expect(t, execute(t, root), Incomplete, "AG-SRC-002", "other/go.go")
	})
	t.Run("unsupported_target", func(t *testing.T) {
		p := fixturePolicy()
		p.Profiles[0].GOOS = "unreal"
		root := fixture(t, p, map[string]string{"base.go": "package nebula\n"})
		expect(t, execute(t, root), Incomplete, "AG-SRC-003", "")
	})
	t.Run("symlink", func(t *testing.T) {
		root := fixture(t, fixturePolicy(), map[string]string{"base.go": "package nebula\n"})
		if e := os.Symlink("base.go", filepath.Join(root, "link.go")); e != nil {
			t.Fatal(e)
		}
		expect(t, execute(t, root), Incomplete, "AG-SRC-000", "")
	})
}

